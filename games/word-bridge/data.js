/* ===========================================================
   Word Bridge — the question bank
   -----------------------------------------------------------
   Every round asks a question like "Name an animal that lives
   in the ocean". You answer with a word, and EVERY LETTER of
   your answer becomes a plank of your bridge — so a long
   answer carries you further across the canyon.

   Each question has:
     q     the question
     top   THE SHOWCASE ANSWERS — a dozen answers a kid would
           actually recognise. The rival bot only ever says one of
           these, and the 💡 hint only ever points at one, so the
           game never suggests an obscure dictionary word it dug
           out of WordNet.
     ok    every answer the game ACCEPTS (the long tail included)
     pics  OPTIONAL. Answers with a picture, for the little kids
           who tap instead of typing. A question needs at least
           3 of these to appear in Tap mode.

   ⭐ THE RULE FOR THIS FILE: a kid who types a REAL answer must
   never be told "I don't know that one". If you ever watch one
   of them get turned down, add the word here — that's the whole
   fix. There are plenty of categories too, so a single race
   never asks the same thing twice.

   WHERE THE LISTS COME FROM. The obvious answers were written by
   hand; the long tail was then sourced from reference data so it
   isn't limited to what anyone could remember:

     • WordNet (princeton) — walked "is a kind of" downwards from
       a seed word, which is exactly category membership: every
       hyponym of "edible fruit", "bird", "musical instrument"…
     • world-countries — every country name
     • minecraft-data — the real mob list for the current version

   That pass is author-time only, in tools/build-word-lists.mjs;
   nothing here is fetched at runtime and the game still ships as
   plain files. Scientific names ("Abramis brama") and people's
   names are screened out on the way in — see the script.

   ⚠️ SCREENED FOR KIDS. WordNet is a dictionary for grown-ups, so
   the raw hyponym walk dragged in anatomy, alcohol, weapons and
   some very old racial slurs. Those are stripped out of this file
   (and duplicates with them). If you ever regenerate the lists,
   run that screen again before shipping — a five-year-old typing
   a word and being told "nice, 4 planks!" is not a joke you get
   to make twice.

   Answers are matched loosely by word-bridge.js: capitals,
   spaces, hyphens, a leading "a/an/the", a trailing "s" and
   spelling slips are all forgiven, so "Ice Cream", "an icecream",
   "ice creams" and "ice creem" all count.
   =========================================================== */

