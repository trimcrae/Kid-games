#!/usr/bin/env node
/* ===========================================================
   fetch-expedition-satellite.mjs — the view from space.
   -----------------------------------------------------------
   For every expedition in games/photo-expedition/data.js, fetches a
   stack of real satellite views centred on the site from NASA's GIBS
   service (Blue Marble: public domain, no API key), each one zoomed in
   further than the last, so the game can "fly in from space" the way
   Google Earth does before the 3D walk begins.

   Saves games/photo-expedition/satellite/<site>-<n>.jpg and writes
   satellite/manifest.js with the width in degrees and kilometres of
   every view. Runs in GitHub Actions (open internet); the sandboxes
   can't reach gibs.earthdata.nasa.gov.

   Usage: node tools/fetch-expedition-satellite.mjs [--force]
   =========================================================== */
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GAME = resolve(ROOT, "games/photo-expedition");
const OUT = resolve(GAME, "satellite");
const FORCE = process.argv.includes("--force");
const exists = (p) => access(p).then(() => true).catch(() => false);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/* widths of the views in degrees of longitude: from a whole hemisphere down to
   about 200 km across, which is as close as Blue Marble's 500 m pixels look good */
const LEVELS = [90, 30, 10, 4, 2];
const SIZE = 1024;
const LAYER = "BlueMarble_ShadedRelief_Bathymetry";
const WMS = "https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi";
const UA = "kid-games-photo-expedition/1.0 (https://github.com/trimcrae/kid-games; family arcade)";

async function loadSites() {
  const src = await readFile(resolve(GAME, "data.js"), "utf8");
  const ctx = {}; vm.createContext(ctx);
  vm.runInContext(src + "\nthis.SITES = SITES;", ctx);
  return ctx.SITES;
}

async function fetchView(lat, lon, widthDeg, attempt = 1) {
  // keep the view square in degrees; at high latitudes the map is stretched, which is what a flat map does
  const half = widthDeg / 2, halfLat = Math.min(half, 89.9 - Math.abs(lat)) ;
  const latC = Math.max(-90 + half, Math.min(90 - half, lat));
  const bbox = [latC - half, lon - half, latC + half, lon + half];          // EPSG:4326 in WMS 1.3.0 is lat,lon order
  const url = WMS + "?" + new URLSearchParams({ SERVICE: "WMS", REQUEST: "GetMap", VERSION: "1.3.0", LAYERS: LAYER, CRS: "EPSG:4326", BBOX: bbox.join(","), WIDTH: String(SIZE), HEIGHT: String(SIZE), FORMAT: "image/jpeg" });
  try {
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error("HTTP " + res.status);
    const type = res.headers.get("content-type") || "";
    if (!type.startsWith("image/")) throw new Error("not an image (" + type + ")");
    return { buf: Buffer.from(await res.arrayBuffer()), bbox };
  } catch (e) {
    if (attempt >= 4) throw e;
    await sleep(2000 * attempt);
    return fetchView(lat, lon, widthDeg, attempt + 1);
  }
}

async function main() {
  await mkdir(OUT, { recursive: true });
  const sites = await loadSites();
  const manifest = {};
  let fetched = 0, failed = 0;
  for (const s of sites) {
    manifest[s.id] = [];
    for (let i = 0; i < LEVELS.length; i++) {
      const file = `${s.id}-${i}.jpg`, path = resolve(OUT, file);
      const w = LEVELS[i];
      const km = Math.round(w * 111 * Math.cos(s.lat * Math.PI / 180));
      if (!FORCE && (await exists(path))) { manifest[s.id].push({ file, deg: w, km }); continue; }
      process.stdout.write(`• ${s.id} ${w}° … `);
      try {
        const { buf } = await fetchView(s.lat, s.lon, w);
        await writeFile(path, buf);
        manifest[s.id].push({ file, deg: w, km });
        fetched++;
        console.log(Math.round(buf.length / 1024) + " KB");
        await sleep(300);
      } catch (e) { failed++; console.log("failed: " + (e && e.message ? e.message : e)); }
    }
    if (!manifest[s.id].length) delete manifest[s.id];
  }
  const body = "/* Generated by tools/fetch-expedition-satellite.mjs — do not edit by hand.\n" +
    "   Real satellite views of every expedition from NASA's Blue Marble (public domain,\n" +
    "   via the GIBS service), from a hemisphere down to about 200 km across. */\n" +
    "window.SATELLITE_MANIFEST = " + JSON.stringify(manifest, null, 1) + ";\n";
  await writeFile(resolve(OUT, "manifest.js"), body);
  console.log(`\nDone: ${fetched} fetched, ${failed} failed.`);
}
main().catch((e) => { console.error(e); process.exit(1); });
